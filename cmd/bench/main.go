// bench turns the raw benchmark results under bench/raw into
// docs/benchmarks.md: per workload and configuration, the median of the
// runs with the minimum and maximum.
//
//	go run ./cmd/bench bench/raw docs/benchmarks.md
package main

import (
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Cell is one run, as bench/run.sh writes it.
type Cell struct {
	Config   string  `json:"config"`
	Workload string  `json:"workload"`
	Run      int     `json:"run"`
	WallNS   float64 `json:"wall_ns"`
	Ops      float64 `json:"ops"`
	NS       float64 `json:"ns"`
	RPS      float64 `json:"rps"`
	P99MS    float64 `json:"p99_ms"`
	CPUTicks float64 `json:"sensor_cpu_ticks"`
	RSSKB    float64 `json:"sensor_rss_kb"`
	Events   float64 `json:"events"`
	Drops    float64 `json:"drops"`
}

// Clock ticks per second of /proc/<pid>/stat on Linux.
const ticksPerSecond = 100

var (
	configs   = []string{"none", "tephra-all", "tephra-alerts", "tephra-enforce", "falco", "tetragon"}
	workloads = []string{"exec", "file", "network", "idle"}
	labels    = map[string]string{
		"none":           "No sensor",
		"tephra-all":     "Tephra, every event exported",
		"tephra-alerts":  "Tephra, alerts only",
		"tephra-enforce": "Tephra, alerts only, enforcement on",
		"falco":          "Falco (modern eBPF, default rules)",
		"tetragon":       "Tetragon (default tracing)",
	}
	workloadText = map[string]string{
		"exec":    "Exec-heavy: 20,000 fork and exec of /bin/true on two CPUs. Throughput in execs per second.",
		"file":    "File-heavy: unpack and compile BusyBox 1.37.0 on two CPUs. Throughput is builds per hour.",
		"network": "Network-heavy: 30,000 HTTP requests to nginx, 32 concurrent, a new connection each. Throughput in requests per second; p99 latency in milliseconds.",
		"idle":    "Idle: 60 seconds with nothing running. Only the sensor's own cost.",
	}
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: bench <raw dir> <output.md>")
		os.Exit(2)
	}
	cells, err := load(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "bench:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[2], []byte(render(cells)), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "bench:", err)
		os.Exit(1)
	}
}

func load(dir string) (map[string]map[string][]Cell, error) {
	out := map[string]map[string][]Cell{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".json") {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var c Cell
		if err := json.Unmarshal(data, &c); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if out[c.Workload] == nil {
			out[c.Workload] = map[string][]Cell{}
		}
		out[c.Workload][c.Config] = append(out[c.Workload][c.Config], c)
		return nil
	})
	return out, err
}

// stat is the median with the minimum and maximum.
type stat struct{ med, min, max float64 }

func summarise(xs []float64) stat {
	if len(xs) == 0 {
		return stat{}
	}
	s := append([]float64(nil), xs...)
	sort.Float64s(s)
	n := len(s)
	med := s[n/2]
	if n%2 == 0 {
		med = (s[n/2-1] + s[n/2]) / 2
	}
	return stat{med, s[0], s[n-1]}
}

func of(cells []Cell, f func(Cell) float64) stat {
	xs := make([]float64, len(cells))
	for i, c := range cells {
		xs[i] = f(c)
	}
	return summarise(xs)
}

func throughput(w string, c Cell) float64 {
	switch w {
	case "exec":
		return c.Ops / (c.NS / 1e9)
	case "file":
		return 3600 / (c.NS / 1e9)
	case "network":
		return c.RPS
	}
	return 0
}

func (s stat) String() string {
	return fmt.Sprintf("%s [%s–%s]", num(s.med), num(s.min), num(s.max))
}

func num(x float64) string {
	switch {
	case x >= 100:
		return fmt.Sprintf("%.0f", x)
	case x >= 10:
		return fmt.Sprintf("%.1f", x)
	}
	return fmt.Sprintf("%.2f", x)
}

func render(all map[string]map[string][]Cell) string {
	var b strings.Builder
	b.WriteString("# Benchmarks\n\n")
	b.WriteString("Generated by `go run ./cmd/bench bench/raw docs/benchmarks.md` from the raw results in [bench/raw](../bench/raw); do not edit by hand.\n\n")
	b.WriteString("**Read this first.** The numbers come from one shared-tenancy cloud VM running a kind cluster, with the workload on two pinned CPUs of one node. They compare the configurations with each other on that machine and say nothing about any other. Each cell is the median of its runs, with the minimum and maximum in brackets; a wide bracket means the cloud VM's noise was large next to the difference being measured.\n\n")
	b.WriteString("Sensor CPU is the sensor's processes on the workload's node, in percent of one CPU over the run; memory is their resident set at the end of the run. Events per second and drops are Tephra's own kernel counters; the other sensors count differently and are not shown there.\n\n")
	for _, w := range workloads {
		byConfig := all[w]
		if len(byConfig) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", strings.ToUpper(w[:1])+w[1:], workloadText[w])
		base := 0.0
		if cs := byConfig["none"]; len(cs) > 0 && w != "idle" {
			base = of(cs, func(c Cell) float64 { return throughput(w, c) }).med
		}
		header := "| Configuration | Runs |"
		sep := "|---|---|"
		if w != "idle" {
			header += " Throughput | vs no sensor |"
			sep += "---|---|"
		}
		if w == "network" {
			header += " p99 ms |"
			sep += "---|"
		}
		header += " Sensor CPU % | Sensor RSS MB | Events/s | Drops |"
		sep += "---|---|---|---|"
		b.WriteString(header + "\n" + sep + "\n")
		for _, cfg := range configs {
			cs := byConfig[cfg]
			if len(cs) == 0 {
				continue
			}
			row := fmt.Sprintf("| %s | %d |", labels[cfg], len(cs))
			if w != "idle" {
				tp := of(cs, func(c Cell) float64 { return throughput(w, c) })
				rel := "–"
				if base > 0 {
					rel = fmt.Sprintf("%+.1f%%", (tp.med/base-1)*100)
				}
				row += fmt.Sprintf(" %s | %s |", tp, rel)
			}
			if w == "network" {
				row += fmt.Sprintf(" %s |", of(cs, func(c Cell) float64 { return c.P99MS }))
			}
			cpu := of(cs, func(c Cell) float64 { return c.CPUTicks / ticksPerSecond / (c.WallNS / 1e9) * 100 })
			rss := of(cs, func(c Cell) float64 { return c.RSSKB / 1024 })
			ev, drops := "–", "–"
			if strings.HasPrefix(cfg, "tephra") {
				ev = of(cs, func(c Cell) float64 { return c.Events / (c.WallNS / 1e9) }).String()
				total := 0.0
				for _, c := range cs {
					total += c.Drops
				}
				drops = fmt.Sprintf("%.0f", total)
			}
			if cfg == "none" {
				row += " – | – | – | – |"
			} else {
				row += fmt.Sprintf(" %s | %s | %s | %s |", cpu, rss, ev, drops)
			}
			b.WriteString(row + "\n")
		}
		b.WriteString("\n")
	}
	return b.String()
}
