package harness

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Report is what coverage.json holds and coverage.md is rendered from.
type Report struct {
	Date    string    `json:"date"`
	Sensor  string    `json:"sensor"`
	Kernel  string    `json:"kernel"`
	Results []*Result `json:"results"`
	// FalsePositives is the latest false-positive run, if one was made.
	FalsePositives *FPResult `json:"false_positives,omitempty"`
}

// FPResult is the outcome of a false-positive run.
type FPResult struct {
	Date    string `json:"date"`
	Sensor  string `json:"sensor"`
	Kernel  string `json:"kernel"`
	Minutes int    `json:"minutes"`
	// Alerts counts what fired, by rule, level and namespace.
	Alerts []FPAlert `json:"alerts"`
	Drops  uint64    `json:"ring_buffer_drops"`
}

// FPAlert is one row of a false-positive run.
type FPAlert struct {
	Rule      string `json:"rule"`
	Level     string `json:"level"`
	Namespace string `json:"namespace"`
	Count     int    `json:"count"`
	// Example is the process of one such alert.
	Example string `json:"example"`
}

// Serious counts the alerts of level high or critical.
func (f *FPResult) Serious() int {
	n := 0
	for _, a := range f.Alerts {
		if a.Level == "high" || a.Level == "critical" {
			n += a.Count
		}
	}
	return n
}

// LoadReport reads coverage.json, or returns an empty report if there is
// none yet.
func LoadReport(path string) (*Report, error) {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return &Report{}, nil
	}
	if err != nil {
		return nil, err
	}
	r := &Report{}
	if err := json.Unmarshal(data, r); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return r, nil
}

// Merge replaces the results of the scenarios in results and keeps the
// others, so that a run of a few scenarios updates the report without
// emptying it.
func (r *Report) Merge(results []*Result) {
	byID := map[string]*Result{}
	for _, res := range r.Results {
		byID[res.ID] = res
	}
	for _, res := range results {
		byID[res.ID] = res
	}
	r.Results = r.Results[:0]
	for _, res := range byID {
		r.Results = append(r.Results, res)
	}
	sort.Slice(r.Results, func(i, j int) bool { return r.Results[i].ID < r.Results[j].ID })
}

// Write stores the report as dir/coverage.json and dir/coverage.md.
func (r *Report) Write(dir string) error {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "coverage.json"), append(data, '\n'), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "coverage.md"), []byte(r.Markdown()), 0o644)
}

func seconds(ms int64) string {
	if ms <= 0 {
		return "—"
	}
	return fmt.Sprintf("%.1f s", float64(ms)/1000)
}

// Markdown renders the report.
func (r *Report) Markdown() string {
	var b strings.Builder
	b.WriteString("# Tephra coverage report\n\n")
	b.WriteString("Generated by `harness run`; do not edit by hand. Each scenario runs a real technique in a throwaway namespace of the lab cluster and is judged by the alerts found in Loki afterwards.\n\n")
	fmt.Fprintf(&b, "| | |\n|---|---|\n| Date | %s |\n| Sensor | `%s` |\n| Kernel | %s |\n\n", r.Date, r.Sensor, r.Kernel)

	counts := map[string]int{}
	var drops uint64
	for _, res := range r.Results {
		counts[res.Verdict()]++
		drops += res.Drops
	}
	fmt.Fprintf(&b, "**%d scenarios: %d detected, %d partial, %d missed", len(r.Results), counts[Detected], counts[Partial], counts[Missed])
	if counts["error"] > 0 {
		fmt.Fprintf(&b, ", %d could not be run", counts["error"])
	}
	fmt.Fprintf(&b, ".** Ring buffer drops during the runs: %d.\n\n", drops)

	b.WriteString("## Detection scenarios\n\n")
	b.WriteString("| ID | Scenario | Expected | Verdict | Event after | Visible after | Also fired |\n|---|---|---|---|---|---|---|\n")
	var notes []string
	for _, res := range r.Results {
		var rules []string
		var slowest int64
		for _, rr := range res.Rules {
			mark := rr.Rule
			if rr.Verdict != Detected {
				mark += " (" + rr.Verdict + ")"
			}
			rules = append(rules, mark)
			slowest = max(slowest, rr.LatencyMS)
			if rr.Why != "" {
				notes = append(notes, fmt.Sprintf("%s, %s: %s.", res.ID, rr.Rule, rr.Why))
			}
		}
		if res.Error != "" {
			notes = append(notes, fmt.Sprintf("%s could not be run: %s.", res.ID, res.Error))
		}
		if res.Note != "" {
			notes = append(notes, fmt.Sprintf("%s: %s", res.ID, res.Note))
		}
		also := strings.Join(res.AlsoFired, ", ")
		if also == "" {
			also = "—"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | **%s** | %s | %s | %s |\n",
			res.ID, res.Title, strings.Join(rules, ", "), res.Verdict(), seconds(slowest), seconds(res.VisibleMS), also)
	}
	b.WriteString("\n\"Event after\" is the time from the start of the technique to the kernel event that raised the alert. \"Visible after\" is the time until every expected alert could be queried through Grafana; it includes the harness's own one-second polling.\n\n")
	b.WriteString("R019 (a process becomes root without running a setuid binary) has no live scenario: reproducing it needs a kernel exploit. It is covered by a rule test on a synthetic event (`rules/testdata/R019.*.jsonl`).\n")
	if len(notes) > 0 {
		b.WriteString("\n### Notes\n\n")
		for _, n := range notes {
			b.WriteString("- " + n + "\n")
		}
	}

	if f := r.FalsePositives; f != nil {
		b.WriteString("\n## False-positive run\n\n")
		fmt.Fprintf(&b, "%d minutes of ordinary workloads with every rule enabled: nginx under HTTP load, PostgreSQL under pgbench, an in-cluster image build, and rolling updates. Run on %s, sensor `%s`, kernel %s.\n\n", f.Minutes, f.Date, f.Sensor, f.Kernel)
		fmt.Fprintf(&b, "**High or critical alerts: %d.** Ring buffer drops: %d.\n\n", f.Serious(), f.Drops)
		if len(f.Alerts) == 0 {
			b.WriteString("No alert of any level fired.\n")
		} else {
			b.WriteString("| Rule | Level | Namespace | Count | Example process |\n|---|---|---|---|---|\n")
			for _, a := range f.Alerts {
				fmt.Fprintf(&b, "| %s | %s | %s | %d | `%s` |\n", a.Rule, a.Level, a.Namespace, a.Count, strings.ReplaceAll(a.Example, "|", "\\|"))
			}
		}
	}
	return b.String()
}
