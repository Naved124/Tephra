package harness

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// DropsReported is the measured verdict of a flooding evasion that went
// undetected while the sensor reported ring buffer drops: the gap is
// visible.
const DropsReported = "drops reported"

// Measured is the verdict of an evasion scenario as measured.
func (r *Result) Measured() string {
	v := r.Verdict()
	if v == Missed && r.DropsVisible {
		return DropsReported
	}
	return v
}

// PredictionHeld says whether the measurement matches the prediction. A
// flooding scenario predicted detected also holds when drops were reported,
// which is what the design asks of it.
func (r *Result) PredictionHeld() bool {
	m := r.Measured()
	return m == r.Predicted || (m == DropsReported && r.Predicted == Detected)
}

// EvasionReport is what evasion.json holds and evasion.md is rendered from.
type EvasionReport struct {
	Date    string    `json:"date"`
	Sensor  string    `json:"sensor"`
	Kernel  string    `json:"kernel"`
	Results []*Result `json:"results"`
}

// Write writes evasion.json and evasion.md into dir.
func (r *EvasionReport) Write(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "evasion.json"), append(data, '\n'), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "evasion.md"), []byte(r.Markdown()), 0o644)
}

// Markdown renders the measured results. The explanations of each miss are
// written by hand under docs/evasions/; this page holds only what was
// measured.
func (r *EvasionReport) Markdown() string {
	var b strings.Builder
	b.WriteString("# Evasion results\n\n")
	b.WriteString("Generated by `harness run --evasions`; do not edit by hand. ")
	b.WriteString("Each scenario tries to get past a detection; the prediction is the one in section 8 of the design. ")
	b.WriteString("A result that differs from the prediction corrects it and is not a test failure. ")
	b.WriteString("The analysis of each finding is in [evasions/](evasions/).\n\n")
	fmt.Fprintf(&b, "Run on %s, sensor %s, kernel %s.\n\n", r.Date, r.Sensor, r.Kernel)
	b.WriteString("| ID | Evasion | Rules | Predicted | Measured | Prediction | Other rules fired | Drops | Agent restarts |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	for _, res := range r.Results {
		var rules []string
		for _, rr := range res.Rules {
			x := rr.Rule + " " + rr.Verdict
			if rr.Why != "" {
				x += " (" + rr.Why + ")"
			}
			rules = append(rules, x)
		}
		held := "held"
		if !res.PredictionHeld() {
			held = "corrected"
		}
		if res.Error != "" {
			held = "not run: " + res.Error
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %d | %d |\n",
			res.ID, res.Title, strings.Join(rules, "; "), res.Predicted, res.Measured(), held,
			dash(strings.Join(res.AlsoFired, ", ")), res.Drops, res.AgentRestarts)
	}
	b.WriteString("\n")
	for _, res := range r.Results {
		if res.Note != "" {
			fmt.Fprintf(&b, "- **%s.** %s\n", res.ID, strings.TrimSpace(res.Note))
		}
	}
	return b.String()
}

func dash(s string) string {
	if s == "" {
		return "–"
	}
	return s
}
